import json
from pathlib import Path

import numpy as np
from torch.utils.data import Dataset

try:
    from imageio.v3 import imread
except ImportError:
    from imageio import imread

from preprocess_data import encoding_token


class SECOND_CC_AUG_Dataset(Dataset):
    """Dataset loader for SECOND-CC-AUG change captioning.

    Expected image layout::

        data_path/
          train/rgb/A/*.png
          train/rgb/B/*.png
          val/rgb/A/*.png
          val/rgb/B/*.png
          test/rgb/A/*.png
          test/rgb/B/*.png

    The list, vocabulary, and token files are generated by
    ``preprocess_second_cc_aug.py``.
    """

    # Per-channel RGB statistics calculated from all paired A/B images in the
    # SECOND-CC-AUG training split. Values are in the original [0, 255] scale.
    DEFAULT_MEAN = [129.19640632352719, 132.26077096093235, 135.2791886520657]
    DEFAULT_STD = [58.50616130843085, 56.9136562080445, 57.3852617483448]

    def __init__(
        self,
        data_path,
        list_path,
        split,
        max_length=23,
        allow_unknown=0,
        vocab_file=None,
        token_path=None,
        mean=None,
        std=None,
    ):
        if split not in {"train", "val", "test"}:
            raise ValueError(
                f"Unsupported split {split!r}; expected train, val, or test."
            )

        self.data_path = Path(data_path)
        self.list_path = Path(list_path)
        self.token_path = Path(token_path) if token_path is not None else None
        self.split = split
        self.max_length = max_length
        self.allow_unknown = allow_unknown
        self.mean = np.asarray(
            mean if mean is not None else self.DEFAULT_MEAN,
            dtype=np.float32,
        ).reshape(3, 1, 1)
        self.std = np.asarray(
            std if std is not None else self.DEFAULT_STD,
            dtype=np.float32,
        ).reshape(3, 1, 1)

        split_file = self.list_path / f"{self.split}.txt"
        if not split_file.is_file():
            raise FileNotFoundError(f"Split list not found: {split_file}")

        with split_file.open("r", encoding="utf-8") as file:
            self.img_info = [line.strip() for line in file if line.strip()]

        self.word_vocab = None
        if vocab_file is not None:
            vocab_path = self.list_path / f"{vocab_file}.json"
            if not vocab_path.is_file():
                raise FileNotFoundError(f"Vocabulary not found: {vocab_path}")
            with vocab_path.open("r", encoding="utf-8") as file:
                self.word_vocab = json.load(file)

        self.files = []
        for list_entry in self.img_info:
            if self.split == "train":
                try:
                    filename, token_id_text = list_entry.rsplit("-", 1)
                    token_id = int(token_id_text)
                except (ValueError, TypeError) as error:
                    raise ValueError(
                        f"Invalid training list entry: {list_entry!r}. "
                        "Expected 'filename-caption_id'."
                    ) from error
            else:
                filename = list_entry
                token_id = None

            image_a = self.data_path / self.split / "rgb" / "A" / filename
            image_b = self.data_path / self.split / "rgb" / "B" / filename

            token_file = None
            if self.token_path is not None:
                token_file = self.token_path / f"{Path(filename).stem}.txt"

            self.files.append(
                {
                    "img_A": image_a,
                    "img_B": image_b,
                    "token": token_file,
                    "token_id": token_id,
                    "img_ids": filename,
                }
            )

    def __getitem__(self, index):
        datafiles = self.files[index]
        img_ids = datafiles["img_ids"]

        img_a_path = datafiles["img_A"]
        img_b_path = datafiles["img_B"]

        if not img_a_path.is_file():
            raise FileNotFoundError(f"Image A not found: {img_a_path}")
        if not img_b_path.is_file():
            raise FileNotFoundError(f"Image B not found: {img_b_path}")

        img_A = np.asarray(imread(img_a_path), dtype=np.float32)
        img_B = np.asarray(imread(img_b_path), dtype=np.float32)

        if img_A.ndim != 3 or img_A.shape[-1] != 3:
            raise ValueError(
                f"Expected RGB image at {img_a_path}, got shape {img_A.shape}."
            )
        if img_B.ndim != 3 or img_B.shape[-1] != 3:
            raise ValueError(
                f"Expected RGB image at {img_b_path}, got shape {img_B.shape}."
            )
        if img_A.shape != img_B.shape:
            raise ValueError(
                f"Image pair shape mismatch for {img_ids}: "
                f"A={img_A.shape}, B={img_B.shape}."
            )

        # HWC -> CHW, followed by dataset-specific normalization.
        img_A = np.moveaxis(img_A, -1, 0)
        img_B = np.moveaxis(img_B, -1, 0)
        img_A = (img_A - self.mean) / self.std
        img_B = (img_B - self.mean) / self.std

        token_file = datafiles["token"]
        if token_file is not None:
            if self.word_vocab is None:
                raise ValueError(
                    "vocab_file must be provided when token_path is used."
                )
            if not token_file.is_file():
                raise FileNotFoundError(f"Token file not found: {token_file}")

            with token_file.open("r", encoding="utf-8") as file:
                caption_list = json.load(file)

            if not caption_list:
                raise ValueError(f"No captions found in token file: {token_file}")

            token_all = np.zeros(
                (len(caption_list), self.max_length),
                dtype=np.int64,
            )
            token_all_len = np.zeros(
                (len(caption_list), 1),
                dtype=np.int64,
            )

            for caption_index, tokens in enumerate(caption_list):
                token_encode = encoding_token(
                    tokens,
                    self.word_vocab,
                    allow_unknown=self.allow_unknown == 1,
                )

                if len(token_encode) > self.max_length:
                    raise ValueError(
                        f"Caption length {len(token_encode)} exceeds "
                        f"max_length={self.max_length} in {token_file}."
                    )

                token_all[caption_index, :len(token_encode)] = token_encode
                token_all_len[caption_index] = len(token_encode)

            token_id = datafiles["token_id"]
            if token_id is not None:
                if token_id < 0 or token_id >= len(caption_list):
                    raise IndexError(
                        f"Caption id {token_id} is out of range for {token_file}."
                    )
                selected_id = token_id
            else:
                selected_id = np.random.randint(len(caption_list))

            token = token_all[selected_id]
            token_len = token_all_len[selected_id].item()
        else:
            token_all = np.zeros(1, dtype=np.int64)
            token_all_len = np.zeros(1, dtype=np.int64)
            token = np.zeros(1, dtype=np.int64)
            token_len = 0

        return (
            img_A.copy(),
            img_B.copy(),
            token_all.copy(),
            token_all_len.copy(),
            token.copy(),
            np.asarray(token_len),
            img_ids,
        )

    def __len__(self):
        return len(self.files)
